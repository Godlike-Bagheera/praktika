def _normalize(text: str) -> str:
    """leetspeak-подмены: цифры, похожие на буквы."""
    for d, l in (("3", "з"), ("6", "б"), ("0", "о"), ("1", "и"), ("4", "ч"), ("7", "т")):
        text = text.replace(d, l)
    return text


def _match_in_whitelisted_word(text: str, start: int, end: int) -> bool:
    """True, если совпадение лежит целиком внутри whitelist-слова."""
    i = start
    while i > 0 and text[i - 1].isalpha():
        i -= 1
    j = end
    n = len(text)
    while j < n and text[j].isalpha():
        j += 1
    return text[i:j].lower() in _WHITELIST


def contains_profanity(text: str, strict: bool = False) -> bool:
    """True, если в тексте найдена нецензурная лексика (кириллица, обфускация, латиница).

    strict=True дополнительно включает мягкий мат (нахер, похер, дерьмо) —
    используется при создании/редактировании сообщений и тем.
    """
    if not text:
        return False
    if _latin_hit(text):
        return True
    if _translit_hit(text):
        return True
    variants = [text, _normalize(text)]
    patterns = _COMPILED + (_SOFT_COMPILED if strict else [])
    for pattern in patterns:
        for source in variants:
            for m in pattern.finditer(source):
                if not _match_in_whitelisted_word(source, m.start(), m.end()):
                    return True
    return False

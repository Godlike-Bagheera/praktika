# Транслит латиницей: zaebal, pizdec, blyad, xyi, yebanij и т.п. (только на
# чисто-латинских токенах — чтобы «мебельный», «подоесть» и т.п. не матчились)
_TRANSLIT_RE = re.compile(
    r"(?i)(?:^|(?<=[^a-zа-яё]))"
    r"(?:"
    r"(?:za|na|po|ot|vy|raz|ob|s|pro)?x[yу]+[eё3]?(?:б|6)?(?:й|я|и|у|a|i)?\b"   # xyi, xuy, hui, zaхуй
    r"|cyx+\b"                                                                                       # cyx (лат.)
    r"|cy(?:ka|kа|па|ba|6а)"                                                              # cyka/cyka с масками
    r"|x[yuу]{2,}(?=\b)"                                                                  # xyu, xyy и т.п. (только x-база, 2+ гласных)
    r"|\b[a-z]{0,3}[yeё][бb](?:al|ali|an|a[тt][ьb]|on|yt|u[чc]h?|i[тt]s?)\b"   # zaebal, yeban, ebanit (\b в начале!)
    r"|p[iy1][zs][dc][aeiouy]"                                                 # pizdec, pizda, pzdya
    r"|\bblyat\b|\bblyad\b|\bblya\b|\bbljad\b"                                 # blyat/blyad — только целые слова
    r"|xyena|xyepa"
    r")"
)


def _token_whitelisted(text: str, start: int, end: int) -> bool:
    """Слово (в границах букв/цифр), содержащее совпадение, есть в whitelist."""
    i = start
    while i > 0 and (text[i - 1].isalnum() or text[i - 1] in "@#$*"):
        i -= 1
    j = end
    n = len(text)
    while j < n and (text[j].isalnum() or text[j] in "@#$*"):
        j += 1
    return text[i:j].lower() in _WHITELIST


def _translit_hit(text: str) -> bool:
    for token in re.finditer(_TRANSLIT_RE, text):
        if not _token_whitelisted(text, token.start(), token.end()):
            return True
    return False

# Транслит/латинский мат — по исходному тексту (до нормализации)
_LATIN_PATTERNS = [
    re.compile(r"(?i)(?:^|(?<=[^a-zа-яё]))(?:h|x)[uуy]y\b"),          # huy/xuy (латиницей, y в конце)
    re.compile(r"(?i)\bcy+k+a+\b|\bsu+k+a+\b|\bx+y+[e3ё]+[pa]*\b"),  # cyka/suka, xyepa/xyena транслит
    re.compile(r"(?i)\bf+u+c+k+\b|\bfuck(?:ed|ing|er|s)?\b|(?:mother|farm)[-\s]?f+u+c+k+\s?[a-z]*"),
    re.compile(r"(?i)\bsh+i+t+\b|\bbull?sh*i*t+\b"),
    re.compile(r"(?i)\bb+i+t+c+h+\b"),
    re.compile(r"(?i)\ba+s+s+h+o+l+e\b|\bast[- ]?hole\b"),
    re.compile(r"(?i)\bcunt\b|\bdickhead\b|\bwank(er|ed|ing)?\b"),
    re.compile(r"(?i)\bslut\b|\bwh[o0]r[e3]\b|\bn[i1]gg+[e3]?r\b"),
    re.compile(r"(?i)\byo?u?b[a44]n[a-z]{0,5}m[uy]\b"),  # yobanymu и варианты
]

def _latin_hit(text: str) -> bool:
    return any(p.search(text) for p in _LATIN_PATTERNS)

